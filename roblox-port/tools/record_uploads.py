"""Merge upload results ({key: assetId}) into studio/assets.json and regenerate
studio/game/shared/Assets.lua, the only place Roblox asset ids live in the game code.

Usage: python record_uploads.py <roblox-port dir> [results.json]
"""
import json
import os
import sys

port = sys.argv[1]
path = os.path.join(port, "studio", "assets.json")
assets = json.load(open(path)) if os.path.exists(path) else {}
if len(sys.argv) > 2:
    res = json.load(open(sys.argv[2]))
    ok = {k: str(v) for k, v in res.items() if str(v).isdigit()}
    assets.update(ok)
    bad = {k: v for k, v in res.items() if not str(v).isdigit()}
    if bad:
        print("not uploaded:", json.dumps(bad, indent=1)[:2000])
json.dump(dict(sorted(assets.items())), open(path, "w"), indent=1)


def rid(k):
    return f"rbxassetid://{assets[k]}" if k in assets else ""


groups = {"Fx": "fx_", "Gui": "gui_", "Skins": "skin_"}
lines = ["-- GENERATED by tools/record_uploads.py from studio/assets.json. Do not edit by hand.",
         "local A = {}"]
for name, pre in groups.items():
    lines.append(f"A.{name} = {{")
    for k in sorted(assets):
        if k.startswith(pre):
            lines.append(f'\t["{k[len(pre):]}"] = "{rid(k)}",')
    lines.append("}")
heroes = sorted({k.split("_", 1)[1].rsplit("_", 1)[0] for k in assets if k.startswith("face_")} |
                {k.split("_", 1)[1] for k in assets if k.startswith("model_") and not k.startswith("model_map_")} |
                {k.split("_", 1)[1] for k in assets if k.startswith(("model_", "package_")) and not k.startswith(("model_map_", "package_code"))})
heroes = [h for h in heroes if not h.startswith("hub_")]
lines.append("A.Heroes = {")
for h in heroes:
    faces = ", ".join(f'"{rid(f"face_{h}_{i}")}"' for i in range(8))
    model = assets.get(f"model_{h}", "")
    pkg = assets.get(f"package_{h}", "")
    lines.append(f'\t{h} = {{ model = {model or "nil"}, package = {pkg or "nil"}, faces = {{ {faces} }} }},')
lines.append("}")
sprites = sorted((k for k in assets if k.startswith("sound_sprite_v2_")), key=lambda k: int(k.rsplit("_", 1)[1]))
lines.append("A.SoundSprites = { " + ", ".join(f'"{rid(k)}"' for k in sprites) + " }")
lines.append(f'A.SoundSprite = "{rid(sprites[0]) if sprites else rid("sound_sprite")}"')
lines.append("A.Hub = {")  # social zone models (port_zone.py files and merged props)
for k in sorted(x for x in assets if x.startswith("hub_")):
    lines.append(f'\t["{k[4:]}"] = {assets[k]},')
lines.append("}")
for k in ("package_code", "model_map_OrbitalArena"):
    lines.append(f"A.{k} = {assets.get(k, 'nil')}")
lines.append("return A")
open(os.path.join(port, "studio", "game", "shared", "Assets.lua"), "w").write("\n".join(lines) + "\n")
print(f"assets.json: {len(assets)} ids; Assets.lua written (heroes {heroes})")
